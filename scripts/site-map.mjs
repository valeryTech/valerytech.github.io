// Assemble Markdown sources before Hugo renders the public HTML navigation maps.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRedirects, generatedDirectory } from './redirects.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const content = path.join(root, 'content/agent-map');
const check = process.argv.includes('--check');

function markdownFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const filename = path.join(directory, entry.name);
    return entry.isDirectory() ? markdownFiles(filename) : filename.endsWith('.md') ? [filename] : [];
  });
}

const temporary = mkdtempSync(path.join(tmpdir(), 'agent-site-map-'));
try {
  // Inventory real Hugo pages and aliases, without yesterday's generated redirects.
  if (!check) rmSync(path.join(root, generatedDirectory), { recursive: true, force: true });
  mkdirSync(path.join(root, generatedDirectory), { recursive: true });
  // Reuse Hugo's published-page inventory, descriptions, and URL resolution.
  // This calls Hugo directly, so it cannot recurse into npm's prebuild hook.
  execFileSync('hugo', [
    '--environment', 'production', '--logLevel', 'error',
    '--destination', temporary, '--noBuildLock',
  ], { cwd: root, stdio: 'pipe' });

  buildRedirects({ root, publicDir: temporary, check });

  const sources = new Map();
  for (const filename of markdownFiles(temporary).filter((filename) => path.basename(filename) === 'site-map.md')) {
    const section = path.relative(temporary, path.dirname(filename));
    const name = section ? `${section}.md` : '_index.md';
    const body = readFileSync(filename, 'utf8');
    const title = body.match(/^# (.+)\n/)?.[1];
    if (!title) throw new Error(`Missing map title: ${filename}`);
    const source = [
      '---',
      `title: ${JSON.stringify(title)}`,
      'description: "Browse documents by collection, follow the main reading links, and discover the website through navigation maps for visitors and agents."',
      'layout: agent-map',
      'outputs: [HTML]',
      'build:',
      '  list: never',
      '---',
      '',
      '<!-- Generated by scripts/site-map.mjs. Edit the notes or map templates, then regenerate. -->',
      '',
      body,
    ].join('\n');
    sources.set(name, source);
  }
  if (!sources.has('_index.md') || sources.size < 2) throw new Error('Hugo did not assemble the main and collection maps');

  const stale = markdownFiles(content).map((filename) => path.relative(content, filename)).filter((name) => !sources.has(name));
  const changed = [...sources].filter(([name, source]) => !existsSync(path.join(content, name)) || readFileSync(path.join(content, name), 'utf8') !== source);
  if (check) {
    if (stale.length || changed.length) {
      throw new Error(`Generated map Markdown is stale. Run make site-map.\n${[...stale, ...changed.map(([name]) => name)].join('\n')}`);
    }
    console.log(`All ${sources.size} Markdown map sources are up to date.`);
  } else {
    mkdirSync(content, { recursive: true });
    for (const [name, source] of changed) {
      const target = path.join(content, name);
      mkdirSync(path.dirname(target), { recursive: true });
      writeFileSync(target, source);
    }
    for (const name of stale) rmSync(path.join(content, name));
    console.log(`Assembled ${sources.size} Markdown maps in content/agent-map/. Hugo renders them at /agent-map/.`);
  }
} catch (error) {
  console.error(error.message);
  if (error.stderr) console.error(error.stderr.toString());
  process.exitCode = 1;
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
